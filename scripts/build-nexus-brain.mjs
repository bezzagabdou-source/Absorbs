/**
 * NEXUS BRAIN — corpus ingestion.
 *
 * The "huge databases" the assistant reasons over are fetched from the internet
 * ONCE, validated, then shipped inside the repo as compact JSON, so at runtime
 * retrieval is offline, instant and deterministic (no API keys, no rate limits,
 * no hallucinated communes).
 *
 * Sources (all public, fetched through the GitHub API — the only hosts this
 * sandbox can reach):
 *   · riadh2002/algeria-69-wilayas-1541-communes  → 69 wilayas + 1541 communes
 *     (names in Arabic + French, daïra, postal code, coordinates)
 *   · dibabdelkrimyt98/json-files-data-algeria     → universities, filières,
 *     university residences
 *
 * Run:  node scripts/build-nexus-brain.mjs            (writes src/lib/brain/data)
 *       node scripts/build-nexus-brain.mjs --check     (verify without writing)
 */

import { mkdir, writeFile, readFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import path from "node:path";

const OUT = path.join(process.cwd(), "src", "lib", "brain", "data");
const CHECK = process.argv.includes("--check");

/**
 * The corpus is written as TYPED TypeScript modules, not .json: a TS module is
 * understood by Next, by tsc and by plain `node --experimental-strip-types`
 * (JSON imports need an import attribute that bundlers and Node disagree on),
 * which is what lets the smoke tests read the same corpus the server ships.
 */
const TYPES = {
  wilayas: `export interface WilayaRow { code: number; fr: string; ar: string; lat: number | null; lng: number | null }`,
  communes: `export interface CommuneRow { id: number; pc: string; fr: string; ar: string; daira_fr: string; daira_ar: string; w: number; lat: number | null; lng: number | null }`,
  universities: `export interface UniversityRow { cat: string; ar: string; fr: string; w: string }`,
  filieres: `export interface FiliereRow { code: string; domain: string; ar: string }`,
  residences: `export interface ResidenceRow { ar: string; w: string }`,
};
const CONSTS = { wilayas: "WILAYAS", communes: "COMMUNES", universities: "UNIVERSITIES", filieres: "FILIERES", residences: "RESIDENCES" };

function asModule(key, rows) {
  const head = `/* AUTO-GENERATED by scripts/build-nexus-brain.mjs — do not edit by hand.\n   Source: see data/sources.ts · regenerate with: node scripts/build-nexus-brain.mjs */\n\n${TYPES[key]}\n\nexport const ${CONSTS[key]}: ${TYPES[key].match(/interface (\w+)/)[1]}[] = `;
  return head + JSON.stringify(rows) + ";\n";
}

