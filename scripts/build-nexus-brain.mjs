const api = (repo, file) => `https://api.github.com/repos/${repo}/contents/${encodeURIComponent(file)}`;

/**
 * Downloads through curl: some sandboxes route egress for curl but not for
 * Node's own fetch, and a corpus builder that silently returns nothing is worse
 * than one that uses the tool that works. `--fail` makes a bad status an error.
 */
function get(url) {
  try {
    return execFileSync(
      "curl",
      ["-sS", "--fail", "--max-time", "60", "-H", "accept: application/vnd.github+json", "-H", "user-agent: nexus-brain-builder", url],
      { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
    );
  } catch (e) {
    throw new Error(`curl failed for ${url}: ${String(e.message).split("\n")[0]}`);
  }
}

async function fetchJson(repo, file) {
  const raw = get(api(repo, file));
  if (!raw.trim()) throw new Error(`${repo}/${file} → empty response`);
  const body = JSON.parse(raw);
  if (!body?.content) throw new Error(`${repo}/${file} → no content (${body?.message ?? "unknown"})`);
  const text = Buffer.from(body.content, "base64").toString("utf8");
  return JSON.parse(text);
}

/**
 * Keeps only what the retriever uses, and normalises the five different shapes
 * these datasets come in into one row = one knowledge card.
 */
function flatten(key, data) {
  if (key === "wilayas") {
    return (data ?? []).map((r) => ({ code: Number(r.code), fr: r.name ?? "", ar: r.name_ar ?? "", lat: Number(r.latitude) || null, lng: Number(r.longitude) || null }));
  }
  if (key === "communes") {
    return (data ?? []).map((r) => ({
      id: Number(r.id), pc: String(r.post_code ?? ""), fr: r.name ?? "", ar: r.name_ar ?? "",
      daira_fr: r.daira ?? "", daira_ar: r.daira_ar ?? "", w: Number(r.wilaya_code ?? 0),
      lat: Number(r.latitude) || null, lng: Number(r.longitude) || null,
    }));
  }
  if (key === "universities") {
    const out = [];
    for (const [cat, list] of Object.entries(data ?? {})) {
      for (const u of Array.isArray(list) ? list : []) {
        const ar = u["الاسم"] ?? u.nom ?? u.name ?? "";
        if (!ar) continue;
        out.push({ cat, ar, fr: u.nom_fr ?? u.name_latin ?? "", w: u["الولاية"] ?? u.wilaya ?? "" });
      }
    }
    return out;
  }
  if (key === "filieres") {
    const out = [];
    for (const d of data?.domains ?? []) {
      for (const f of d.filieres ?? []) out.push({ code: d.code ?? "", domain: d.nom ?? "", ar: typeof f === "string" ? f : f.nom ?? "" });
    }
    return out;
  }
  if (key === "residences") {
    const out = [];
    for (const dir of data?.directions_oeuvres_universitaires ?? []) {
      for (const r of dir.residences_universitaires ?? []) {
        out.push({ ar: r.nom ?? "", w: dir.wilaya?.nom ?? dir.nom_direction ?? "" });
      }
    }
    return out;
  }
  return Array.isArray(data) ? data : [];
}

async function main() {
  await mkdir(OUT, { recursive: true });
  const manifest = { builtAt: new Date().toISOString(), entries: {}, sources: [] };
  let total = 0;

  for (const src of SOURCES) {
    process.stdout.write(`· ${src.key.padEnd(13)} ${src.repo}/${src.file} … `);
    try {
      const rows = await fetchJson(src.repo, src.file);
      const slimmed = flatten(src.key, rows);
      if (!Array.isArray(slimmed) || slimmed.length < src.min) {
        throw new Error(`too few rows (${Array.isArray(slimmed) ? slimmed.length : "?"} < ${src.min})`);
      }
      const mod = asModule(src.key, slimmed);
      if (!CHECK) await writeFile(path.join(OUT, `${src.key}.ts`), mod, "utf8");
      else await readFile(path.join(OUT, `${src.key}.ts`), "utf8");
      total += slimmed.length;
      manifest.entries[src.key] = { rows: slimmed.length, bytes: mod.length };
      manifest.sources.push({ key: src.key, repo: src.repo, file: src.file, license: src.license, note: src.note });
      console.log(`${String(slimmed.length).padStart(5)} rows · ${(mod.length / 1024).toFixed(0)} KB`);
    } catch (e) {
      console.log(`FAILED — ${e.message}`);
      process.exitCode = 1;
    }
  }

  if (!CHECK) {
    const srcMod =
      "/* AUTO-GENERATED by scripts/build-nexus-brain.mjs — provenance of the shipped corpus. */\n\n" +
      "export interface BrainSource { key: string; repo: string; file: string; license: string; note: string }\n\n" +
      `export const BRAIN_BUILT_AT = ${JSON.stringify(manifest.builtAt)};\n\n` +
      `export const BRAIN_SOURCES: BrainSource[] = ${JSON.stringify(manifest.sources, null, 1)};\n\n` +
      `export const BRAIN_ROWS: Record<string, number> = ${JSON.stringify(Object.fromEntries(Object.entries(manifest.entries).map(([k, v]) => [k, v.rows])), null, 1)};\n\n` +
      `export const BRAIN_BYTES: number = ${Object.values(manifest.entries).reduce((s, e) => s + e.bytes, 0)};\n`;
    await writeFile(path.join(OUT, "sources.ts"), srcMod, "utf8");
  }
  console.log(`\n${CHECK ? "checked" : "wrote"} ${total.toLocaleString("ar-DZ")} rows → ${path.relative(process.cwd(), OUT)}`);
  for (const s of manifest.sources) console.log(`  ${s.key}: ${s.note}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
