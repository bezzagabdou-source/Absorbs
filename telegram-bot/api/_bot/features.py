def total_count():
    return sum(len(v) for v in all_features().values())


def handle(ctx):
    rest = take(ctx, "الميزات", "عدد الميزات", "features", "المميزات", "قوة البوت")
    if rest is not None:
        cats = all_features()
        total = total_count()
        lines = [f"⚡ <b>ميزات Absorbs: {total}+ ميزة!</b> 🔥\n"]
        for cat, items in cats.items():
            lines.append(f"{cat}: <b>{len(items)}</b> ميزة")
        lines.append("\n📋 اكتب (الاوامر) للقائمة التفاعلية، أو اختر فئة:")
        rows = []
        keys = list(cats.keys())
        for i in range(0, len(keys), 2):
            row = []
            for k in keys[i:i + 2]:
                idx = keys.index(k)
                row.append(btn(f"{k} ({len(cats[k])})", data=f"feat:{idx}"))
            rows.append(row)
        ctx.reply("\n".join(lines), markup=keyboard(rows))
        return True
    return False


def callback(ctx, parts):
    tg, cid = ctx.tg, ctx.chat_id
    cq = ctx.update["callback_query"]
    if parts[0] != "feat" or len(parts) < 2:
        return
    if parts[1] == "back":
        tg.answer_callback(cq["id"])
        cats = all_features()
        total = total_count()
        lines = [f"⚡ <b>ميزات Absorbs: {total}+ ميزة!</b> 🔥\n"]
        for cat, items in cats.items():
            lines.append(f"{cat}: <b>{len(items)}</b> ميزة")
        keys = list(cats.keys())
        rows = []
        for i in range(0, len(keys), 2):
            row = [btn(f"{k} ({len(cats[k])})", data=f"feat:{keys.index(k)}") for k in keys[i:i + 2]]
            rows.append(row)
        tg.edit(cid, cq["message"]["message_id"], "\n".join(lines), markup=keyboard(rows))
        return
    try:
        idx = int(parts[1])
    except ValueError:
        return
    cats = all_features()
    keys = list(cats.keys())
    if 0 <= idx < len(keys):
        cat = keys[idx]
        items = cats[cat]
        tg.answer_callback(cq["id"])
        text = f"<b>{cat} ({len(items)} ميزة):</b>\n\n" + "\n".join(f"• {esc(x)}" for x in items)
        if len(text) > 3900:
            tg.edit(cid, cq["message"]["message_id"], f"<b>{cat} ({len(items)} ميزة):</b>",
                    markup=keyboard([[btn("🏠 رجوع", data="feat:back")]]))
            chunk = ""
            for x in items:
                if len(chunk) + len(x) > 3500:
                    tg.send(cid, chunk)
                    chunk = ""
                chunk += f"• {esc(x)}\n"
            if chunk:
                tg.send(cid, chunk)
        else:
            tg.edit(cid, cq["message"]["message_id"], text,
                    markup=keyboard([[btn("🏠 رجوع", data="feat:back")]]))
