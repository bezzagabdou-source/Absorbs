def _me(ctx):
    return getattr(ctx.tg, "me", None) or {}


def _bot_username(ctx):
    un = _me(ctx).get("username", "")
    if not un:
        try:
            un = (ctx.tg.get_me() or {}).get("username", "")
        except Exception:
            un = ""
    return (un or "").lower()


def _mentioned(ctx):
    un = _bot_username(ctx)
    text = ctx.text or ""
    low = text.lower()
    if un and ("@" + un) in low:
        return True
    me_id = _me(ctx).get("id")
    for e in (ctx.msg.get("entities", []) or []) + (ctx.msg.get("caption_entities", []) or []):
        if e.get("type") == "text_mention" and me_id and e.get("user", {}).get("id") == me_id:
            return True
        if e.get("type") == "mention" and un:
            seg = text[e.get("offset", 0):e.get("offset", 0) + e.get("length", 0)].lower()
            if seg == "@" + un:
                return True
    return False


def _replied_to_bot(ctx):
    rm = ctx.reply_msg
    me_id = _me(ctx).get("id")
    return bool(rm and me_id and rm.get("from", {}).get("id") == me_id)


