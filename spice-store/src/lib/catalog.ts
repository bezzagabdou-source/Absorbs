const featured = [
  "فلفل أحمر (حلو، حار)", "كمون (حب، مرحي)", "راس الحانوت", "زعتر",
  "كركم (حب، مرحي)", "قرفة مرحية وعود وحتى السيلانكية", "العسل الملكي", "بذور الشيا",
];

export function initialProduct(name: string, categoryIndex: number, image: string) {
  const rank = featured.indexOf(name);
  let productImage = image;
  if (name.includes("فلفل أحمر")) productImage = "/images/paprika.png";
  else if (name.includes("كمون")) productImage = "/images/cumin.png";
  else if (name.includes("قرفة")) productImage = "/images/cinnamon.png";
  else if (name.includes("كركم")) productImage = "/images/saffron.png";
  else if (name.includes("زعتر")) productImage = "/images/zaatar.png";
  const featuredPrices: Record<string, string> = {
    "فلفل أحمر (حلو، حار)": "280", "كمون (حب، مرحي)": "350", "راس الحانوت": "400",
    "زعتر": "250", "كركم (حب، مرحي)": "300", "قرفة مرحية وعود وحتى السيلانكية": "450",
    "العسل الملكي": "2200", "بذور الشيا": "550", "العسل الحرة": "3500",
  };
  return {
    name,
    price: featuredPrices[name] ?? ["250", "300", "1800", "700"][categoryIndex],
    status: (name === "العسل الحرة" ? "limited" : "available") as "available" | "limited",
    image: productImage,
    sortOrder: rank < 0 ? 100 : rank,
  };
}
